/**
 * @file grammar.c
 * @brief Gramática predictiva de Piper y construcción de su tabla LL(1).
 *
 * La gramática conserva los delimitadores de parser.y. Las expresiones se
 * separan por precedencia para eliminar la recursión izquierda: los sufijos
 * repetibles representan operadores asociativos a la izquierda, Potencia'
 * vuelve a Potencia para conservar asociatividad a la derecha y Comparación'
 * no se repite para mantener las comparaciones no asociativas.
 */

